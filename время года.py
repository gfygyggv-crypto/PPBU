s = input("Введите время года: ")
s = s.lower() # приравнение регистра
if s == "лето":
    print(f"{s.capitalize()} - прекрасное время для отдыха на пляже!")
elif s == "осень":
    print('Хорошее время для прогулок в парке')
elif s == "зима":
    print('Катаемся на лыжах')
elif s == "весна":
    print('Пробуждение природы')
else:
    print(f"{s} - это не время года!")